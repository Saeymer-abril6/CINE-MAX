-- ============================================================
--  ESQUEMA DE CINEMAX
--  Ventas de entradas y dulcería
--  Compatible con H2 (modo PostgreSQL) y PostgreSQL
-- ============================================================

CREATE TABLE IF NOT EXISTS unidad_medida (
    id_unidad_medida INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(30) NOT NULL UNIQUE,
    abreviatura      VARCHAR(10) NOT NULL
);

CREATE TABLE IF NOT EXISTS categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(30) NOT NULL UNIQUE,
    descripcion  VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS perfil (
    id_perfil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario    VARCHAR(30)  NOT NULL UNIQUE,
    clave      VARCHAR(100) NOT NULL,
    nombre     VARCHAR(80)  NOT NULL,
    id_perfil  INTEGER      NOT NULL,
    estado     VARCHAR(15)  NOT NULL DEFAULT 'Activo',
    CONSTRAINT fk_usuario_perfil FOREIGN KEY (id_perfil)
        REFERENCES perfil (id_perfil)
);

CREATE TABLE IF NOT EXISTS cliente (
    dni       VARCHAR(8)  PRIMARY KEY,
    nombre    VARCHAR(80) NOT NULL,
    direccion VARCHAR(120),
    celular   VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS pelicula (
    id_pelicula   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo        VARCHAR(100) NOT NULL UNIQUE,
    genero        VARCHAR(40)  NOT NULL,
    duracion_min  INTEGER      NOT NULL,
    clasificacion VARCHAR(10)  NOT NULL,
    estado        VARCHAR(15)  NOT NULL DEFAULT 'En cartelera'
);

CREATE TABLE IF NOT EXISTS sala (
    id_sala   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(30) NOT NULL UNIQUE,
    tipo      VARCHAR(10) NOT NULL,
    capacidad INTEGER     NOT NULL
);

CREATE TABLE IF NOT EXISTS funcion (
    id_funcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pelicula INTEGER NOT NULL,
    id_sala     INTEGER NOT NULL,
    fecha       DATE    NOT NULL,
    hora        TIME    NOT NULL,
    estado      VARCHAR(15) NOT NULL DEFAULT 'Programada',
    CONSTRAINT fk_funcion_pelicula FOREIGN KEY (id_pelicula)
        REFERENCES pelicula (id_pelicula),
    CONSTRAINT fk_funcion_sala FOREIGN KEY (id_sala)
        REFERENCES sala (id_sala),
    CONSTRAINT uq_funcion_sala_fecha_hora UNIQUE (id_sala, fecha, hora)
);

CREATE TABLE IF NOT EXISTS producto (
    id_producto      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(80) NOT NULL UNIQUE,
    id_categoria     INTEGER     NOT NULL,
    id_unidad_medida INTEGER     NOT NULL,
    costo            NUMERIC(10,2) NOT NULL,
    porce_util       NUMERIC(5,2)  NOT NULL DEFAULT 0.30,
    stock            INTEGER       NOT NULL DEFAULT 0,
    controla_stock   BOOLEAN       NOT NULL DEFAULT TRUE,
    estado           VARCHAR(15)   NOT NULL DEFAULT 'Activo',
    CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria),
    CONSTRAINT fk_producto_unidad FOREIGN KEY (id_unidad_medida)
        REFERENCES unidad_medida (id_unidad_medida)
);

CREATE TABLE IF NOT EXISTS venta (
    id_venta     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni_cliente  VARCHAR(8) NOT NULL,
    id_usuario   INTEGER    NOT NULL,
    fecha_venta  DATE       NOT NULL,
    neto_total   NUMERIC(10,2) NOT NULL,
    igv          NUMERIC(10,2) NOT NULL,
    precio_total NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_venta_cliente FOREIGN KEY (dni_cliente)
        REFERENCES cliente (dni),
    CONSTRAINT fk_venta_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario)
);

CREATE TABLE IF NOT EXISTS venta_detalle (
    id_venta_detalle INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta     INTEGER NOT NULL,
    id_producto  INTEGER NOT NULL,
    id_funcion   INTEGER,
    precio_unit  NUMERIC(10,2) NOT NULL,
    porce_util   NUMERIC(5,2)  NOT NULL,
    cantidad     INTEGER       NOT NULL,
    neto_total   NUMERIC(10,2) NOT NULL,
    utilidad     NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta)
        REFERENCES venta (id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES producto (id_producto),
    CONSTRAINT fk_detalle_funcion FOREIGN KEY (id_funcion)
        REFERENCES funcion (id_funcion)
);

CREATE INDEX IF NOT EXISTS idx_funcion_pelicula ON funcion (id_pelicula);
CREATE INDEX IF NOT EXISTS idx_funcion_sala ON funcion (id_sala);
CREATE INDEX IF NOT EXISTS idx_funcion_fecha ON funcion (fecha);
CREATE INDEX IF NOT EXISTS idx_producto_categoria ON producto (id_categoria);
CREATE INDEX IF NOT EXISTS idx_producto_unidad ON producto (id_unidad_medida);
CREATE INDEX IF NOT EXISTS idx_venta_cliente ON venta (dni_cliente);
CREATE INDEX IF NOT EXISTS idx_venta_usuario ON venta (id_usuario);
CREATE INDEX IF NOT EXISTS idx_detalle_venta ON venta_detalle (id_venta);
CREATE INDEX IF NOT EXISTS idx_detalle_producto ON venta_detalle (id_producto);
CREATE INDEX IF NOT EXISTS idx_detalle_funcion ON venta_detalle (id_funcion);
